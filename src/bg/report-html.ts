import type { SiteReport } from '../core/rules';
import { PHASE_LABEL } from '../core/phase';
import { SOURCE_LABEL } from '../core/consent';
import { CATEGORY_LABEL } from '../core/trackers';
import type { Phase } from '../core/types';

export function esc(s: unknown): string {
  return String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]!));
}

const PHASES: Phase[] = ['after_reject', 'after_partial', 'pre_choice', 'no_banner', 'after_accept'];

/** Self-contained, printable HTML evidence report. All values escaped. */
export function renderHtmlReport(rep: SiteReport, meta: { version: string; trackerDb: string }): string {
  const r = rep.receipt;
  const receiptLine = r
    ? `You ${r.choice === 'rejected' ? 'rejected tracking' : r.choice === 'accepted' ? 'accepted tracking' : r.choice === 'partial' ? 'allowed some purposes' : 'made a choice'} on ${esc(new Date(r.ts).toLocaleString())} (recorded from: ${esc(SOURCE_LABEL[r.source])}).`
    : 'No consent choice was recorded for this site.';
  const rows = rep.orgs.filter((o) => o.tier !== 'functional').map((o) => {
    const cells = PHASES.map((p) => {
      const st = o.phases[p];
      if (!st) return '<td>–</td>';
      const bits = [];
      if (st.requests) bits.push(`${st.requests} req${st.dataSending ? ` (${st.dataSending} sending data)` : ''}`);
      if (st.cookiesSet.length) bits.push(`cookies set: ${esc(st.cookiesSet.join(', '))}`);
      if (st.cookiesSent.length) bits.push(`cookies sent: ${esc(st.cookiesSent.join(', '))}`);
      if (st.fingerprint.length) bits.push(`fingerprint APIs: ${esc(st.fingerprint.join(', '))}`);
      if (st.blocked) bits.push(`${st.blocked} blocked`);
      return `<td>${bits.join('<br>') || '–'}</td>`;
    }).join('');
    return `<tr><td><b>${esc(o.orgName)}</b><br><small>${esc(o.category ? CATEGORY_LABEL[o.category] : 'Unknown third party')}${o.country ? ' · ' + esc(o.country) : ''}</small><br><small>${esc(o.hosts.join(', '))}</small></td>${cells}</tr>`;
  }).join('');
  const findings = rep.findings.map((f) => `<li><b>[${esc(f.severity.toUpperCase())}] ${esc(f.rule)}</b> ${esc(f.text)} <small>(confidence: ${esc(f.confidence)}, first seen ${esc(new Date(f.firstTs).toLocaleTimeString())})</small></li>`).join('');
  const receipts = rep.receipts.map((x) => `<li>${esc(new Date(x.ts).toLocaleString())}: ${esc(x.choice)} via ${esc(SOURCE_LABEL[x.source])}${x.raw ? ' (' + esc(x.raw) + ')' : ''}${x.gpc ? ' · GPC sent' : ''}</li>`).join('');
  return `<!doctype html><html><head><meta charset="utf-8"><title>See My Trackers: ${esc(rep.site)}</title>
<style>body{font:14px/1.45 system-ui,sans-serif;margin:24px;color:#1b1b1b}table{border-collapse:collapse;width:100%}td,th{border:1px solid #ddd;padding:6px;vertical-align:top;font-size:12px}th{background:#f4f4f4;text-align:left}h1{font-size:20px}small{color:#555}.note{background:#fff8e1;padding:10px;border-radius:6px}</style></head><body>
<h1>Tracking report for ${esc(rep.site)}</h1>
<p>${receiptLine}</p>
<p><b>${rep.counts.afterRejectTrackingOrgs}</b> tracking compan${rep.counts.afterRejectTrackingOrgs === 1 ? 'y was' : 'ies were'} contacted after you rejected · <b>${rep.counts.preChoiceTrackingOrgs}</b> before any choice · ${rep.counts.thirdPartyOrgs} third parties in total.</p>
<h2>Findings</h2><ul>${findings || '<li>No findings.</li>'}</ul>
<h2>Companies</h2><table><tr><th>Company</th>${PHASES.map((p) => `<th>${esc(PHASE_LABEL[p])}</th>`).join('')}</tr>${rows}</table>
<h2>Consent receipts</h2><ul>${receipts || '<li>None</li>'}</ul>
<p class="note">Generated by See My Trackers ${esc(meta.version)} on ${esc(new Date(rep.generatedAt).toLocaleString())}. Company data: Ghostery TrackerDB ${esc(meta.trackerDb)} (CC BY-NC-SA 4.0). These are observations made by your browser, not a legal judgment. The extension cannot see data that sites share server-to-server.</p>
</body></html>`;
}
